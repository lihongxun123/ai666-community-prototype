import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const dir=path.dirname(fileURLToPath(import.meta.url));
const notes=path.dirname(dir);
const source=path.join(notes,'page-requirements-c.json');
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const original=read(source);
const content=read(path.join(dir,'content-pages.json'));
const actions=read(path.join(dir,'action-pages.json'));
const merged=process.argv.includes('--merge')?{...content,...actions}:original;
if(Object.keys(merged).length!==Object.keys(original).length||Object.keys(original).some(k=>!merged[k]))throw Error('Incomplete page coverage');
const ordered=Object.fromEntries(Object.keys(original).map(k=>[k,merged[k]]));
fs.writeFileSync(source,JSON.stringify(ordered,null,2)+'\n');
const common=fs.readFileSync(path.join(dir,'common-rules.md'),'utf8');
fs.writeFileSync(path.join(dir,'common-rules.json'),JSON.stringify({text:common},null,2)+'\n');
const linkage=fs.readFileSync(path.join(dir,'b-c-linkage.md'),'utf8');
const pending=fs.existsSync(path.join(dir,'decisions.md'))?fs.readFileSync(path.join(dir,'decisions.md'),'utf8'):'';
fs.writeFileSync(path.join(dir,'decisions.json'),JSON.stringify({text:pending},null,2)+'\n');
const intro='# AI666 C 端产品需求 · 设计研发版\n\n更新：2026-10-05。包含 ' + Object.keys(ordered).length + ' 个页面定义及 PC、移动端承载规则。\n\n正文规定字段、操作、状态、异常和验收条件；公共规则统一登录、列表、输入、互动、积分、内容管理及草稿行为。研发对接项明确能力、接口和字段的映射责任。\n\n';
const body=Object.entries(ordered).map(([id,text])=>`<!-- page: ${id} -->\n\n${text}`).join('\n\n---\n\n');
fs.writeFileSync(path.join(dir,'AI666_C端产品需求_设计研发版.md'),intro+linkage+'\n\n'+common+'\n\n# 页面需求\n\n'+body+'\n\n'+pending+'\n');
console.log(`Synced ${Object.keys(ordered).length} pages and shared rules`);
